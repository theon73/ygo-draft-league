-- Commissioner controls (YGO-19): undo as its own pick-log row, and pausing the draft.

-- UNDO reverses the latest row still in effect (a pick, auto-pick, skip or make-up); undoes holds
-- that row's sequence. Nothing is deleted: the undone row stays in the log, and everything that
-- reads the log skips rows an UNDO points at. Repeated undos walk back through the log.
alter table draft_pick add column undoes int;
alter table draft_pick drop constraint draft_pick_kind_check;
alter table draft_pick add constraint draft_pick_kind_check check (kind in ('PICK', 'AUTO', 'SKIP', 'UNDO'));
alter table draft_pick drop constraint draft_pick_shape_check;
alter table draft_pick add constraint draft_pick_shape_check check (
    case kind
        when 'PICK' then card_id is not null and made_by is not null and undoes is null
        when 'AUTO' then card_id is not null and made_by is null and undoes is null
        when 'SKIP' then card_id is null and made_by is null and not makeup and undoes is null
        when 'UNDO' then card_id is null and made_by is not null and not makeup and undoes is not null
    end);
create unique index draft_pick_undo_once on draft_pick (season_id, undoes) where undoes is not null;
-- A slot can be made up again after its make-up is undone, so "one make-up per slot" is now checked
-- by the service (under the per-season lock) rather than by an index.
drop index draft_pick_one_makeup;

create or replace view card_holding as
select d.season_id, d.card_id, d.season_player_id, count(*)::int as quantity
from draft_pick d
where d.kind in ('PICK', 'AUTO')
  and not exists (select 1 from draft_pick u where u.season_id = d.season_id and u.undoes = d.sequence)
group by d.season_id, d.card_id, d.season_player_id;

-- Commissioner pauses. While one is open (resumed_at null) nobody picks, the timer stands still and
-- away mode waits. Kept as history: who paused, when, and for how long.
create table draft_pause (
    id         bigint generated by default as identity primary key,
    season_id  bigint      not null references draft (season_id),
    paused_at  timestamptz not null default now(),
    paused_by  bigint      not null references app_user (id),
    resumed_at timestamptz,
    resumed_by bigint      references app_user (id),
    check ((resumed_at is null) = (resumed_by is null)),
    check (resumed_at is null or resumed_at >= paused_at)
);
create unique index draft_pause_one_open on draft_pause (season_id) where resumed_at is null;
