-- The schedule (YGO-25): stages and their matches.
--
-- A season has one or more stages: the regular season now; a play-in and playoffs later (YGO-27).
-- A stage's format says how its matches are made (round-robin now; Swiss, head-to-head, ladder and
-- brackets later). Best-of isn't stored here: it comes from the rules in effect for a match's week
-- (competition.matchBestOf for the regular season), so it can change mid-season like other rules.
create table stage (
    id         bigint generated by default as identity primary key,
    season_id  bigint      not null references season (id),
    kind       text        not null check (kind in ('REGULAR', 'PLAY_IN', 'PLAYOFFS')),
    format     text        not null check (format in ('ROUND_ROBIN')),
    created_at timestamptz not null default now(),
    unique (season_id, kind)
);

-- How a round-robin was laid out: the player order its rotation started from (a random draw), and
-- who made it (null = automatically, when the draft completed). Every reshuffle before week 1 adds a
-- row; the latest is the schedule in force. Kept as history, like seat draws.
create table schedule_draw (
    id           bigint generated by default as identity primary key,
    stage_id     bigint      not null references stage (id),
    player_order bigint[]    not null,   -- season_player ids, in the order the rotation used
    drawn_at     timestamptz not null default now(),
    drawn_by     bigint      references app_user (id)
);
create index schedule_draw_stage_idx on schedule_draw (stage_id, drawn_at desc);

-- Matches. week is the league week it's played in, round the stage's round (one round a week for
-- now, so they match). player_b_id null is a bye: player_a sits the round out. Players can be null
-- later for bracket matches whose players aren't known yet ("winner of match 3"); the round-robin
-- always names player_a. Results (games, reports, confirmations) come with YGO-26.
-- Rows are replaced when the schedule is reshuffled before week 1 (they never happened); once the
-- season's week 1 has begun they're fixed.
create table season_match (
    id          bigint generated by default as identity primary key,
    season_id   bigint not null references season (id),
    stage_id    bigint not null references stage (id),
    week        int    not null check (week >= 1),
    round       int    not null check (round >= 1),
    player_a_id bigint references season_player (id),
    player_b_id bigint references season_player (id),
    check (player_a_id is distinct from player_b_id)
);
create index season_match_stage_week_idx on season_match (stage_id, week);
create index season_match_player_a_idx on season_match (season_id, player_a_id);
create index season_match_player_b_idx on season_match (season_id, player_b_id);
