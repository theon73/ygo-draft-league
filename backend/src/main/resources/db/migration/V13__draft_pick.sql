-- Draft picks (YGO-16): the append-only draft log. Rows are never updated or deleted.
--
-- sequence orders the log (1, 2, 3, ... per season); overall_pick is the board slot the row fills.
-- They match while every row is a PICK, but they're kept apart so later kinds fit without a schema
-- change: an UNDO (YGO-19) is its own row that reopens a slot, so the next PICK fills the same
-- overall_pick again; a timer SKIP or AUTO pick (YGO-18) is a row like any other. For the same
-- reason a card isn't unique per season here: legality (in the pool, not taken, the right turn) is
-- checked by the service under a per-season lock on the draft row.
create table draft_pick (
    id               bigint generated by default as identity primary key,
    season_id        bigint      not null references draft (season_id),
    sequence         int         not null check (sequence > 0),
    kind             text        not null default 'PICK' check (kind in ('PICK')),
    overall_pick     int         not null check (overall_pick > 0),
    season_player_id bigint      not null references season_player (id),   -- the seat the pick belongs to
    card_id          bigint      not null references card (id),
    made_by          bigint      not null references app_user (id),        -- who clicked: the player, or a commissioner for them
    made_at          timestamptz not null default now(),
    unique (season_id, sequence)
);
create index draft_pick_card_idx on draft_pick (season_id, card_id);

-- Who holds what: the ownership projection. For now it's the draft alone; trades and free agency
-- (Phase 4) redefine this view in a later migration, and everything that asks "who owns this card"
-- reads it. quantity is in copies (always 1 per owner with exclusive ownership).
create view card_holding as
select season_id, card_id, season_player_id, count(*)::int as quantity
from draft_pick
where kind = 'PICK'
group by season_id, card_id, season_player_id;
