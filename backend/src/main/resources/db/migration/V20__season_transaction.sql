-- Transactions (YGO-23): executed changes of hands after the draft. Append-only; rows are never
-- updated or deleted. Only executed transactions live here: a trade's proposal, counteroffers and
-- comments (YGO-24) get their own tables, and an accepted trade becomes one of these.
--
-- A free-agent claim is one transaction with two lines: the claimed card (from nobody to the
-- player) and the card they drop (from the player to nobody). week is the league week it executed
-- in (0 = between the draft and week 1); weekly limits count week 0 together with week 1.
create table season_transaction (
    id               bigint generated by default as identity primary key,
    season_id        bigint      not null references season (id),
    kind             text        not null check (kind in ('FREE_AGENCY')),
    season_player_id bigint      not null references season_player (id),   -- whose transaction it is (counts toward their limit)
    week             int         not null check (week >= 0),
    executed_at      timestamptz not null default now(),
    created_by       bigint      not null references app_user (id)         -- who clicked: the player, or a commissioner for them
);
create index season_transaction_player_week_idx on season_transaction (season_id, season_player_id, week);

create table season_transaction_line (
    id             bigint generated by default as identity primary key,
    transaction_id bigint not null references season_transaction (id),
    card_id        bigint not null references card (id),
    from_player_id bigint references season_player (id),   -- null: from free agency
    to_player_id   bigint references season_player (id),   -- null: to free agency
    quantity       int    not null default 1 check (quantity > 0),
    check (from_player_id is not null or to_player_id is not null),
    check (from_player_id is distinct from to_player_id)
);
create index season_transaction_line_tx_idx on season_transaction_line (transaction_id);

-- The ownership history gains the executed lines. Columns stay as in V19 (so card_holding, built on
-- it, is unchanged); two are added at the end: for_player_id is whose action it was (the drafting
-- player, or the transaction's player) and transaction_id groups a transaction's lines.
create or replace view card_ownership_event as
select d.season_id,
       d.card_id,
       null::bigint       as from_player_id,
       d.season_player_id as to_player_id,
       1                  as quantity,
       d.made_at          as at,
       0                  as week,
       'DRAFT'::text      as source,
       d.overall_pick     as draft_pick,
       d.made_by          as made_by,
       d.sequence         as ordinal,          -- int, as in V19 (a view's column types can't change)
       d.season_player_id as for_player_id,
       null::bigint       as transaction_id
from draft_pick d
where d.kind in ('PICK', 'AUTO')
  and not exists (select 1 from draft_pick u where u.season_id = d.season_id and u.undoes = d.sequence)
union all
select t.season_id,
       l.card_id,
       l.from_player_id,
       l.to_player_id,
       l.quantity,
       t.executed_at,
       t.week,
       t.kind,
       null::int,
       t.created_by,
       l.id::int,
       t.season_player_id,
       t.id
from season_transaction t join season_transaction_line l on l.transaction_id = t.id;
