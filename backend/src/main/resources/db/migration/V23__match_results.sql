-- Match results (YGO-26).
--
-- A result is a report: games won by each player (tied games left out, so 1-1 is a draw), or a
-- forfeit recorded by a commissioner. Reports are append-only history; a status says where each one
-- stands, and a match's result is its latest CONFIRMED report.
--   PENDING     a player reported it; waiting for the opponent (auto-confirms after the season's delay)
--   CONFIRMED   final: the opponent confirmed, the delay passed (auto_confirmed), or a commissioner entered it
--   DISPUTED    the opponent disagreed; the commissioners settle it (by entering the result)
--   SUPERSEDED  replaced by a later report or a commissioner's correction
-- games_a / games_b follow the match's player_a / player_b.
create table match_report (
    id               bigint generated by default as identity primary key,
    match_id         bigint      not null references season_match (id),
    season_id        bigint      not null references season (id),
    games_a          int         not null default 0 check (games_a between 0 and 9),
    games_b          int         not null default 0 check (games_b between 0 and 9),
    forfeit          text        check (forfeit in ('A', 'B', 'BOTH')),   -- who forfeited (commissioners only)
    replays          text[]      not null default '{}',                   -- optional links, one per game
    status           text        not null check (status in ('PENDING', 'CONFIRMED', 'DISPUTED', 'SUPERSEDED')),
    by_commissioner  boolean     not null default false,                  -- entered by a commissioner (final at once)
    reported_by      bigint      not null references app_user (id),
    reported_player  bigint      references season_player (id),           -- the player it was reported as; null for a commissioner
    reported_at      timestamptz not null default now(),
    confirmed_by     bigint      references app_user (id),
    confirmed_at     timestamptz,
    auto_confirmed   boolean     not null default false,
    dispute_note     text        check (length(dispute_note) <= 500),
    disputed_by      bigint      references app_user (id),
    disputed_at      timestamptz,
    check (forfeit is null or by_commissioner),
    check ((status = 'CONFIRMED') = (confirmed_at is not null) or status = 'SUPERSEDED')
);
create index match_report_match_idx on match_report (match_id, reported_at desc);
create index match_report_pending_idx on match_report (season_id) where status = 'PENDING';
-- At most one live report (pending, disputed or confirmed) per match.
create unique index match_report_one_live on match_report (match_id) where status <> 'SUPERSEDED';
