-- A season's card pool (YGO-13): the dated pool generated from the rules (TCG cutoff) plus an
-- exception list of hand-picked cards (e.g. just past the cutoff), with per-card flags.
--
-- pool_card is the pool's current state, one row per card. A card's time in the pool is
-- [added_in_week, removed_in_week): week 0 is pre-season, so cards present from the start have
-- added_in_week = 0, and a mid-season addition or removal takes effect from its week. Past weeks
-- are therefore always judged by the pool as it was then. pool_change is the append-only log of
-- every change (who, when, effective week, reason).

create table pool_card (
    id                 bigint generated by default as identity primary key,
    season_id          bigint      not null,
    league_id          bigint      not null,
    card_id            bigint      not null references card (id),
    source             text        not null check (source in ('DATED', 'EXCEPTION')),
    copies             int         not null default 1 check (copies > 0),   -- 1 = exclusive ownership (v1)
    soft_banned        boolean     not null default false,   -- can't be drafted or played
    requires_ownership boolean     not null default false,   -- must be owned to be played (e.g. Polymerization)
    max_playable       int         check (max_playable between 0 and 3),   -- null = the normal limit
    reason             text,                                -- why an exception was added
    added_in_week      int         not null default 0 check (added_in_week >= 0),
    removed_in_week    int         check (removed_in_week >= added_in_week),   -- equal = never in play (removed during setup)
    created_at         timestamptz not null default now(),
    foreign key (season_id, league_id) references season (id, league_id),
    unique (season_id, card_id)
);
create index pool_card_season_idx on pool_card (season_id) where removed_in_week is null;

create table pool_change (
    id                  bigint generated by default as identity primary key,
    season_id           bigint      not null references season (id),
    kind                text        not null check (kind in ('GENERATED', 'ADDED', 'REMOVED', 'FLAGS')),
    card_id             bigint      references card (id),     -- null for whole-pool changes (GENERATED)
    effective_from_week int         not null default 0 check (effective_from_week >= 0),
    detail              jsonb       not null default '{}',   -- e.g. counts, cutoff, flags set
    reason              text,
    created_by          bigint      references app_user (id),
    created_at          timestamptz not null default now()
);
create index pool_change_season_idx on pool_change (season_id, created_at desc);
