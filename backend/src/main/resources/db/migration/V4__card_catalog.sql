-- Global card catalog, synced from YGOPRODeck. TCG only: cards without a TCG release date
-- (OCG-only) and Speed Duel Skill Cards are not imported. Rows are never deleted by the sync,
-- because season pools will reference them.

-- A TCG product. YGOPRODeck set codes are prefixes and are NOT unique (e.g. both 2013 tin
-- waves use CT10), so the set name is the natural key.
create table card_set (
    id         bigint generated by default as identity primary key,
    name       text        not null unique,
    code       text        not null,
    tcg_date   date,                                  -- null for a few promo/unknown products
    card_count int,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);
create index card_set_code_idx on card_set (code);
create index card_set_tcg_date_idx on card_set (tcg_date);

-- Identity: YGOPRODeck's "id" is just whichever artwork it lists first, and that order differs
-- between responses (Dark Magician comes back as 46986414 or 46986420), so it is NOT a key.
-- The sync matches on konami_id (Konami's database id: unique, but missing for a few tokens and
-- unreleased cards), falling back to any shared passcode. passcodes holds every artwork's
-- passcode, which is also its YGOPRODeck image id.
create table card (
    id             bigint generated by default as identity primary key,
    konami_id      int         unique,                -- null for some tokens / not-yet-released cards
    passcodes      bigint[]    not null check (cardinality(passcodes) > 0),  -- ascending
    name           text        not null,
    card_type      text        not null,              -- e.g. 'Effect Monster', 'Spell Card', 'XYZ Monster'
    frame_type     text        not null,              -- e.g. 'effect', 'spell', 'xyz', 'effect_pendulum'
    race           text        not null,              -- monster type, or Spell/Trap subtype ('Quick-Play')
    attribute      text,                              -- monsters only
    level          int,                               -- Main Deck, Fusion, Synchro, Ritual monsters
    rank           int,                               -- Xyz monsters (YGOPRODeck sends this as "level")
    link_rating    int,
    link_markers   text[],
    pendulum_scale int,
    atk            int,                               -- null for '?' and non-monsters
    def            int,                               -- null for '?', Link monsters and non-monsters
    archetype      text,
    description    text        not null,              -- current text; older wording in card_text_version
    tcg_date       date        not null,              -- first TCG release; drives format cutoffs
    ocg_date       date,
    raw            jsonb       not null,              -- source record minus volatile/unstable fields
    content_hash   text        not null,              -- sha-256 of raw; lets the sync skip unchanged cards
    created_at     timestamptz not null default now(),
    updated_at     timestamptz not null default now(),
    check (level is null or rank is null)
);
create index card_passcodes_idx on card using gin (passcodes);   -- "which card has passcode X"
create index card_name_lower_idx on card (lower(name));
create index card_tcg_date_idx on card (tcg_date);
create index card_archetype_idx on card (archetype);

-- One printing of a card in a set at a rarity (e.g. LOB-EN005, Ultra Rare). Replaced wholesale
-- for a card whenever that card changes in the source.
create table card_print (
    id          bigint generated by default as identity primary key,
    card_id     bigint not null references card (id),
    set_id      bigint not null references card_set (id),
    print_code  text   not null,                      -- e.g. 'LOB-EN005'
    rarity      text   not null,                      -- e.g. 'Ultra Rare'
    rarity_code text,                                 -- e.g. '(UR)'
    unique (card_id, set_id, print_code, rarity)
);
create index card_print_set_idx on card_print (set_id);

-- Superseded card text, for formats that play older wording (e.g. Goat). Each row is text that
-- was in effect until valid_until (exclusive). Text as of date D = the row with the earliest
-- valid_until > D, otherwise card.description. Curated by hand for now; the sync never touches it.
create table card_text_version (
    id          bigint generated by default as identity primary key,
    card_id     bigint      not null references card (id),
    valid_until date        not null,
    description text        not null,
    source      text        not null,                 -- where the wording came from (URL or note)
    created_at  timestamptz not null default now(),
    unique (card_id, valid_until)
);

-- One row per sync attempt: an audit trail and the source version used to skip no-op runs.
create table catalog_sync (
    id             bigint generated by default as identity primary key,
    started_at     timestamptz not null default now(),
    finished_at    timestamptz,
    status         text        not null check (status in ('RUNNING', 'SUCCEEDED', 'SKIPPED', 'FAILED')),
    trigger        text        not null check (trigger in ('SCHEDULED', 'MANUAL')),
    source_version text,                              -- YGOPRODeck database_version
    sets_upserted  int,
    cards_added    int,
    cards_updated  int,
    cards_ignored  int,                               -- OCG-only, Skill Cards
    error          text
);
create index catalog_sync_started_idx on catalog_sync (started_at desc);
