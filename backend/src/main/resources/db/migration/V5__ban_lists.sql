-- Ban lists. Two kinds share one model:
--   * official: dated TCG lists shipped as YAML files in the repo (league_id null, official_key set)
--   * custom:   owned by one league, started from scratch or copied from any list it can see
--
-- Lists are append-only: every change creates a new revision, and season rules reference a
-- specific revision. Editing a list therefore never rewrites the rules a past season played under.
-- A card that isn't in a revision's entries is unlimited.

create table ban_list (
    id             bigint generated by default as identity primary key,
    league_id      bigint      references league (id),
    official_key   text        unique,                -- e.g. 'tcg/2008-03-01' (file path); official only
    name           text        not null,
    effective_date date,                              -- when an official list took effect
    created_by     bigint      references app_user (id),   -- null for official lists
    created_at     timestamptz not null default now(),
    check ((league_id is null) = (official_key is not null)),
    check (official_key is null or effective_date is not null),
    unique (league_id, name)                          -- custom list names unique within a league
);
create index ban_list_league_idx on ban_list (league_id);

create table ban_list_revision (
    id                    bigint generated by default as identity primary key,
    ban_list_id           bigint      not null references ban_list (id),
    revision              int         not null check (revision > 0),
    based_on_revision_id  bigint      references ban_list_revision (id),  -- what a copy started from
    content_hash          text        not null,      -- sha-256 of the sorted entries; skips no-op revisions
    note                  text,                      -- e.g. file source URL, or the commissioner's reason
    created_by            bigint      references app_user (id),
    created_at            timestamptz not null default now(),
    unique (ban_list_id, revision)
);

create table ban_list_entry (
    revision_id bigint not null references ban_list_revision (id),
    card_id     bigint not null references card (id),
    status      text   not null check (status in ('FORBIDDEN', 'LIMITED', 'SEMI_LIMITED')),
    primary key (revision_id, card_id)
);
create index ban_list_entry_card_idx on ban_list_entry (card_id);
