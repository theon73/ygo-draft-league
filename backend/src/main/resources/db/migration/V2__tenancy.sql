-- Tenancy model: users, leagues, membership, invites, and league-scoped seasons.
-- See PLANNING.md §0 "What this means for the schema" and §3.
--
-- Enum-like columns are text + check constraints rather than Postgres enums, so adding a
-- value later is a one-line constraint swap instead of an ALTER TYPE dance.

-- ---------------------------------------------------------------------------------------
-- V1 leftovers: the global player list (and its seed of one specific league) goes away.
-- Season participation now goes through league_member. Nothing was ever deployed, so the
-- V1 season tables are rebuilt rather than migrated.
-- ---------------------------------------------------------------------------------------
drop table season_player;
drop table season;
drop table player;

-- ---------------------------------------------------------------------------------------
-- Accounts
-- ---------------------------------------------------------------------------------------
create table app_user (
    id           bigint generated by default as identity primary key,
    display_name text        not null,
    avatar_url   text,
    created_at   timestamptz not null default now()
);

-- One row per external login (Google, Discord, ...). A user may link several.
create table user_identity (
    id         bigint generated by default as identity primary key,
    user_id    bigint      not null references app_user (id) on delete cascade,
    provider   text        not null,                -- e.g. 'google', 'discord'
    subject    text        not null,                -- provider's stable user id
    email      text,
    created_at timestamptz not null default now(),
    unique (provider, subject)
);
create index user_identity_user_idx on user_identity (user_id);

-- ---------------------------------------------------------------------------------------
-- Leagues and membership
-- ---------------------------------------------------------------------------------------
create table league (
    id         bigint generated by default as identity primary key,
    name       text        not null,
    slug       text        not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    created_by bigint      not null references app_user (id),
    created_at timestamptz not null default now()
);

-- A seat in a league. user_id is null for placeholder members (added by the commissioner,
-- claimed later through an invite). Commissioner is a role, so co-commissioners are allowed.
create table league_member (
    id           bigint generated by default as identity primary key,
    league_id    bigint      not null references league (id),
    user_id      bigint      references app_user (id),
    display_name text        not null,
    role         text        not null check (role in ('COMMISSIONER', 'PLAYER', 'VIEWER')),
    created_at   timestamptz not null default now(),
    unique (league_id, user_id),          -- NULLs don't collide, so many placeholders are fine
    unique (league_id, display_name),
    unique (id, league_id)                -- target for composite FKs that pin rows to one league
);
create index league_member_user_idx on league_member (user_id);

-- An invite either grants a role to whoever redeems it (open invite), or hands a specific
-- placeholder member to the redeemer (claim invite). Exactly one of role / member_id is set.
create table league_invite (
    id         bigint generated by default as identity primary key,
    league_id  bigint      not null references league (id),
    code       text        not null unique,
    role       text        check (role in ('COMMISSIONER', 'PLAYER', 'VIEWER')),
    member_id  bigint,
    max_uses   int         check (max_uses > 0),        -- null = unlimited
    use_count  int         not null default 0 check (use_count >= 0),
    expires_at timestamptz,
    revoked_at timestamptz,
    created_by bigint      not null references app_user (id),
    created_at timestamptz not null default now(),
    check ((role is null) <> (member_id is null)),
    check (member_id is null or max_uses = 1),
    foreign key (member_id, league_id) references league_member (id, league_id)
);
create index league_invite_league_idx on league_invite (league_id);

-- ---------------------------------------------------------------------------------------
-- Seasons
-- ---------------------------------------------------------------------------------------
create table season (
    id         bigint generated by default as identity primary key,
    league_id  bigint      not null references league (id),
    name       text        not null,
    status     text        not null default 'SETUP'
                           check (status in ('SETUP', 'DRAFTING', 'ACTIVE', 'COMPLETE')),
    created_at timestamptz not null default now(),
    unique (league_id, name),
    unique (id, league_id)
);

-- A league member taking part in a season. league_id is redundant but lets the two
-- composite FKs guarantee the member and the season belong to the same league.
create table season_player (
    id               bigint generated by default as identity primary key,
    season_id        bigint      not null,
    league_id        bigint      not null,
    league_member_id bigint      not null,
    seat             int         check (seat > 0),
    team_name        text,
    created_at       timestamptz not null default now(),
    foreign key (season_id, league_id)        references season (id, league_id),
    foreign key (league_member_id, league_id) references league_member (id, league_id),
    unique (season_id, league_member_id),
    unique (season_id, seat)
);

-- Versioned rules. Rows are append-only: a change is a new version. The rules in effect for
-- week W are the highest version with effective_from_week <= W. Week 0 is pre-season
-- (setup and draft). rules is parsed into typed records by the app; schema_version tracks
-- the shape of that JSON so old versions can still be read.
create table season_rules (
    id                  bigint generated by default as identity primary key,
    season_id           bigint      not null references season (id),
    version             int         not null check (version > 0),
    effective_from_week int         not null check (effective_from_week >= 0),
    schema_version      int         not null check (schema_version > 0),
    rules               jsonb       not null,
    created_by          bigint      references app_user (id),   -- null = system default
    created_at          timestamptz not null default now(),
    unique (season_id, version)
);
