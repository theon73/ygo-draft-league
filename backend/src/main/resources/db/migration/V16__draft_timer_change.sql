-- Changing the pick timer during a draft (YGO-20). The settings recorded at the start stay as they
-- were; each change is a row here, and the latest one is the timer in force. pick_timer has the
-- shape of the rules' pickTimer, or is null for "no timer". A change restarts the timer of the
-- pick on the clock under the new setting.
create table draft_timer_change (
    id         bigint generated by default as identity primary key,
    season_id  bigint      not null references draft (season_id),
    pick_timer jsonb,
    changed_at timestamptz not null default now(),
    changed_by bigint      not null references app_user (id)
);
create index draft_timer_change_season_idx on draft_timer_change (season_id, changed_at);
