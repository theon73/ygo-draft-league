-- The league's time zone (IANA id, e.g. 'America/Chicago'). Week boundaries, deadlines and draft
-- times are interpreted in it. Existing leagues start at UTC; commissioners can change it.
alter table league add column time_zone text not null default 'UTC';

-- Every seat-order randomization, kept forever, so a draw can't be quietly redone: anyone in the
-- league can see who drew, when, and the result. seat_order is league_member ids, seat 1 first.
create table season_seat_draw (
    id         bigint generated by default as identity primary key,
    season_id  bigint      not null references season (id),
    drawn_by   bigint      not null references app_user (id),
    drawn_at   timestamptz not null default now(),
    seat_order bigint[]    not null check (cardinality(seat_order) > 0)
);
create index season_seat_draw_season_idx on season_seat_draw (season_id, drawn_at desc);
