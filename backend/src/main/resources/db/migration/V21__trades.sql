-- Trades (YGO-24).
--
-- An executed trade is a season_transaction of kind TRADE: season_player_id is the player who made
-- the offer, counterparty_id the one who accepted it. Its cards are ordinary transaction lines (so
-- they reach card_ownership_event and card_holding unchanged), and allowances it moves (this
-- week's free-agent claims or trades) are rows in season_transaction_allowance.
alter table season_transaction drop constraint season_transaction_kind_check;
alter table season_transaction add constraint season_transaction_kind_check check (kind in ('FREE_AGENCY', 'TRADE'));
alter table season_transaction add column counterparty_id bigint references season_player (id);
alter table season_transaction add constraint season_transaction_counterparty_check
    check ((kind = 'TRADE') = (counterparty_id is not null) and counterparty_id is distinct from season_player_id);

-- Allowances moved by a trade. week is the allowance week they apply to (week 0 counts as week 1).
create table season_transaction_allowance (
    id             bigint generated by default as identity primary key,
    transaction_id bigint not null references season_transaction (id),
    kind           text   not null check (kind in ('FREE_AGENCY', 'TRADE')),
    from_player_id bigint not null references season_player (id),
    to_player_id   bigint not null references season_player (id),
    quantity       int    not null check (quantity > 0),
    week           int    not null check (week >= 1),
    check (from_player_id <> to_player_id)
);
create index season_transaction_allowance_tx_idx on season_transaction_allowance (transaction_id);

-- One conversation per pair of players in a season: every offer, counteroffer and message between
-- them. Private to the two players. Designed to become their message history in a later inbox.
create table trade_thread (
    id             bigint generated by default as identity primary key,
    season_id      bigint      not null references season (id),
    player_low_id  bigint      not null references season_player (id),   -- the pair, smaller id first
    player_high_id bigint      not null references season_player (id),
    created_at     timestamptz not null default now(),
    check (player_low_id < player_high_id),
    unique (season_id, player_low_id, player_high_id)
);

-- Offers. Unlike ownership, an offer's status is updated in place (it's a negotiation, not league
-- state); executing one writes the append-only transaction above.
--   OPEN              waiting for the recipient
--   PENDING_APPROVAL  accepted, waiting for a commissioner (when the season's rules ask for approval)
--   EXECUTED          done; transaction_id is the trade
--   DECLINED          the recipient said no; kept, but shown to nobody
--   WITHDRAWN         the proposer took it back
--   CANCELLED         a card in it moved elsewhere (or the season ended); cancel_reason says why
--   REJECTED          a commissioner refused it
-- counter_of links a counteroffer to the offer it answers; both stay acceptable.
create table trade_offer (
    id             bigint generated by default as identity primary key,
    thread_id      bigint      not null references trade_thread (id),
    season_id      bigint      not null references season (id),
    from_player_id bigint      not null references season_player (id),
    to_player_id   bigint      not null references season_player (id),
    status         text        not null default 'OPEN'
                   check (status in ('OPEN', 'PENDING_APPROVAL', 'EXECUTED', 'DECLINED', 'WITHDRAWN', 'CANCELLED', 'REJECTED')),
    counter_of     bigint      references trade_offer (id),
    created_at     timestamptz not null default now(),
    created_by     bigint      not null references app_user (id),
    accepted_at    timestamptz,
    accepted_by    bigint      references app_user (id),
    decided_at     timestamptz,
    decided_by     bigint      references app_user (id),
    transaction_id bigint      references season_transaction (id),
    cancel_reason  text,
    check (from_player_id <> to_player_id),
    check ((status = 'EXECUTED') = (transaction_id is not null))
);
create index trade_offer_thread_idx on trade_offer (thread_id);
create index trade_offer_live_idx on trade_offer (season_id) where status in ('OPEN', 'PENDING_APPROVAL');

-- What each side gives: a card, or a number of this week's allowances.
create table trade_offer_asset (
    id       bigint generated by default as identity primary key,
    offer_id bigint not null references trade_offer (id),
    giver_id bigint not null references season_player (id),
    kind     text   not null check (kind in ('CARD', 'FREE_AGENCY', 'TRADE')),
    card_id  bigint references card (id),
    quantity int    not null default 1 check (quantity > 0),
    check ((kind = 'CARD') = (card_id is not null)),
    check (kind <> 'CARD' or quantity = 1)
);
create index trade_offer_asset_offer_idx on trade_offer_asset (offer_id);
create index trade_offer_asset_card_idx on trade_offer_asset (card_id) where card_id is not null;

-- Messages in a thread, between the two players.
create table trade_message (
    id               bigint generated by default as identity primary key,
    thread_id        bigint      not null references trade_thread (id),
    author_player_id bigint      not null references season_player (id),
    author_user_id   bigint      not null references app_user (id),   -- who typed it (a commissioner for a placeholder)
    body             text        not null check (length(body) between 1 and 1000),
    created_at       timestamptz not null default now()
);
create index trade_message_thread_idx on trade_message (thread_id, created_at);
